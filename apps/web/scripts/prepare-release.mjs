#!/usr/bin/env node
/* Single source of truth for a release is release.json (version-controlled, reviewed in PRs).
 * This script runs before every build/serve/test and:
 *   1. writes src/app/core/release-info.ts so the code knows its own version/schema,
 *   2. writes the same data into ngsw-config.json → appData, so the service worker can tell the
 *      running app what the *new* version is (and whether it is critical) before activating it,
 *   3. keeps package.json "version" in step.
 * The deploy pipeline POSTs release.json to the API (/release/publish) after the CDN upload. */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
// RELEASE_JSON lets test harnesses build "releases" without touching the committed descriptor.
const releasePath = process.env.RELEASE_JSON || join(root, 'release.json');
const release = JSON.parse(readFileSync(releasePath, 'utf8'));
const semver = /^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/;
for (const key of ['version', 'minSupportedVersion']) {
  if (!semver.test(release[key])) throw new Error(`release.json: ${key} must be semver, got ${release[key]}`);
}
if (!Number.isInteger(release.schemaVersion) || release.schemaVersion < 1) throw new Error('release.json: schemaVersion must be a positive integer');
if (release.minSupportedSchema > release.schemaVersion) throw new Error('release.json: minSupportedSchema > schemaVersion');

const info = {
  version: release.version,
  schemaVersion: release.schemaVersion,
  minSupportedVersion: release.minSupportedVersion,
  minSupportedSchema: release.minSupportedSchema,
  critical: !!release.critical,
  channel: release.channel ?? 'stable',
  notes: release.notes ?? '',
};

writeFileSync(
  join(root, 'src/app/core/release-info.ts'),
  `// GENERATED by scripts/prepare-release.mjs from release.json — do not edit.\n` +
    `export const RELEASE = ${JSON.stringify(info, null, 2)} as const;\n`,
);

const ngswPath = join(root, 'ngsw-config.json');
const ngsw = JSON.parse(readFileSync(ngswPath, 'utf8'));
ngsw.appData = info;
writeFileSync(ngswPath, JSON.stringify(ngsw, null, 2) + '\n');

const pkgPath = join(root, 'package.json');
const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
if (!process.env.RELEASE_JSON && pkg.version !== release.version) {
  pkg.version = release.version;
  writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');
}
console.log(`release ${info.version} (schema ${info.schemaVersion}${info.critical ? ', CRITICAL' : ''})`);
